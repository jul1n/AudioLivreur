// Fallback logic and helper functions
let currentLang = 'fr';

function t(key, params = {}) {
    let str = translations[currentLang]?.[key] || translations['en']?.[key] || translations['fr']?.[key] || key;
    for (const [k, v] of Object.entries(params)) {
        str = str.replace(`{${k}}`, v);
    }
    return str;
}

function applyTranslations(lang) {
    if (translations[lang]) {
        currentLang = lang;
    }
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = t(key);
        } else {
            // Check if there are nested elements we should preserve
            if(el.children.length > 0 && !el.innerHTML.includes('<i ')) {
                // Not ideal, but if it has icons, we might overwrite them.
                // We integrated icons into the translation strings for buttons.
            }
            el.innerHTML = t(key);
        }
    });
    window.dispatchEvent(new Event('languageChanged'));
}

window.t = t;
window.applyTranslations = applyTranslations;
